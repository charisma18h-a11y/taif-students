BEGIN;

CREATE TABLE IF NOT EXISTS public.portal_notices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  pinned BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.portal_notices ADD COLUMN IF NOT EXISTS subject TEXT;

CREATE TABLE IF NOT EXISTS public.portal_review_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.portal_review_questions ADD COLUMN IF NOT EXISTS subject TEXT;

CREATE TABLE IF NOT EXISTS public.portal_notice_reads (
  notice_id BIGINT NOT NULL REFERENCES public.portal_notices(id) ON DELETE CASCADE,
  student_id TEXT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  read_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (notice_id, student_id)
);

