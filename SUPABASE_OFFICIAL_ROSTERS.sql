-- Execute once in Supabase SQL Editor, AFTER the portal_courses tables exist.
-- Additive only: does not change or delete students, course enrollments, or group memberships.
BEGIN;
CREATE TABLE IF NOT EXISTS public.portal_official_rosters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES public.portal_courses(id) ON DELETE RESTRICT,
    section TEXT NOT NULL CHECK(section ~ '^[0-9]{2,12}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(course_id, section)
);
CREATE TABLE IF NOT EXISTS public.portal_official_roster_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roster_id BIGINT NOT NULL REFERENCES public.portal_official_rosters(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL CHECK(length(full_name) BETWEEN 5 AND 160),
    normalized_name TEXT NOT NULL,
    linked_student_id TEXT REFERENCES public.students(id) ON DELETE SET NULL,
    import_marker TEXT NOT NULL DEFAULT '',
    UNIQUE(roster_id, normalized_name)
);
CREATE UNIQUE INDEX IF NOT EXISTS portal_roster_one_link_per_student
 ON public.portal_official_roster_entries(roster_id,linked_student_id)
 WHERE linked_student_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS portal_official_roster_course_idx ON public.portal_official_rosters(course_id,section);
CREATE INDEX IF NOT EXISTS portal_official_roster_entries_lookup_idx ON public.portal_official_roster_entries(roster_id,normalized_name);
-- Access is through admin-session-protected Next.js server routes, not direct anonymous database API.
REVOKE ALL ON public.portal_official_rosters FROM anon, authenticated;
REVOKE ALL ON public.portal_official_roster_entries FROM anon, authenticated;
COMMIT;
