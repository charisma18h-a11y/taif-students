-- وش علينا: تجهيز ميزات اللوحة والإعلانات والتنبيهات.
-- شغّل مرة واحدة في مشروع Supabase الذي يشير إليه DATABASE_URL في Vercel.
-- آمن للبيانات: لا DROP ولا TRUNCATE ولا حذف سجلات.
BEGIN;
CREATE TABLE IF NOT EXISTS public.portal_notices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  pinned BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.portal_notices ADD COLUMN IF NOT EXISTS subject TEXT;
CREATE TABLE IF NOT EXISTS public.portal_notice_reads (
  notice_id BIGINT NOT NULL REFERENCES public.portal_notices(id) ON DELETE CASCADE,
  student_id TEXT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  read_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(notice_id,student_id)
);
CREATE TABLE IF NOT EXISTS public.portal_student_progress (
  student_id TEXT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  assignment_id TEXT NOT NULL REFERENCES public.assignments(id) ON DELETE CASCADE,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(student_id,assignment_id)
);
CREATE TABLE IF NOT EXISTS public.portal_timetable (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject TEXT NOT NULL,
  section TEXT NOT NULL,
  weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  starts_at TEXT NOT NULL,
  ends_at TEXT NOT NULL,
  room TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS public.portal_push_subscriptions (
  endpoint TEXT PRIMARY KEY,
  student_id TEXT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS portal_push_by_student ON public.portal_push_subscriptions(student_id);
-- Ensure an existing assignments table has the two optional fields used by the app.
ALTER TABLE public.assignments ADD COLUMN IF NOT EXISTS subject TEXT;
ALTER TABLE public.assignments ADD COLUMN IF NOT EXISTS details TEXT;
ALTER TABLE public.assignments ADD COLUMN IF NOT EXISTS published BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE public.assignments ADD COLUMN IF NOT EXISTS due_date TIMESTAMPTZ;
ALTER TABLE public.assignments ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
-- Prevent direct access with the Supabase public browser key; API uses checked sessions.
REVOKE ALL ON TABLE public.portal_notices, public.portal_notice_reads,
  public.portal_student_progress, public.portal_timetable, public.portal_push_subscriptions
  FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.portal_notices_id_seq, public.portal_timetable_id_seq
  FROM anon, authenticated;
COMMIT;
